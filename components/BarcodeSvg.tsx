const START_CODE_B = 104;
const STOP_CODE = 106;

function encodeCode128B(text: string): number[] {
  const codes: number[] = [START_CODE_B];
  let checksum = START_CODE_B;

  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i) - 32;
    const validCode = code >= 0 && code <= 94 ? code : 0;
    codes.push(validCode);
    checksum += validCode * (i + 1);
  }

  const checkSymbol = checksum % 103;
  codes.push(checkSymbol);
  codes.push(STOP_CODE);

  return codes;
}

interface BarcodeSvgProps {
  text: string;
  height?: number;
  barWidth?: number;
  className?: string;
  style?: React.CSSProperties;
}

export default function BarcodeSvg({
  text,
  height = 48,
  barWidth = 2,
  className = '',
  style = {},
}: BarcodeSvgProps) {
  if (!text) return null;

  const codes = encodeCode128B(text);
  const bars: boolean[] = [];

  for (const code of codes) {
    const pattern = CODE128_PATTERNS[code];
    if (!pattern) continue;

    let isBar = true;
    for (const width of pattern) {
      for (let w = 0; w < width; w++) {
        bars.push(isBar);
      }
      isBar = !isBar;
    }
  }

  const totalModules = bars.length;
  const svgWidth = totalModules * barWidth;

  return (
    <svg
      viewBox={`0 0 ${svgWidth} ${height}`}
      className={`block mx-auto ${className}`}
      style={{
        height: `${height}px`,
        width: 'auto',
        maxWidth: '100%',
        display: 'block',
        margin: '0 auto',
        imageRendering: 'pixelated',
        ...style,
      }}
    >
      <rect width={svgWidth} height={height} fill="#ffffff" />
      {bars.map((isBar, idx) => {
        if (!isBar) return null;
        return (
          <rect
            key={idx}
            x={idx * barWidth}
            y={0}
            width={barWidth}
            height={height}
            fill="#000000"
          />
        );
      })}
    </svg>
  );
}
